# New validation-focused API
def validate_paper(test_file: str) -> dict:
    """
    Validate the academic_paper property on a test class.
    
    Checks:
    1. Paper exists
    2. Word count <= 700
    3. Honesty standards (no overclaiming, limitations acknowledged)
    
    Args:
        test_file: Path to the test file
        
    Returns:
        Validation result dict
    """
    from .paper_generator import _validate_paper_property
    return _validate_paper_property(test_file)


def extract_paper(test_file: str) -> str:
    """
    Extract the academic_paper property from a test class.
    
    Args:
        test_file: Path to the test file
        
    Returns:
        The academic_paper text, or empty string if not found
    """
    from .paper_generator import _extract_paper_property
    return _extract_paper_property(test_file)


