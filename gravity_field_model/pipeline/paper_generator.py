def _extract_paper_property(test_file: str) -> str:
    """
    Extract the academic_paper property from a test class.
    
    Args:
        test_file: Path to the test file
        
    Returns:
        The academic_paper text, or empty string if not found
    """
    import importlib.util
    
    path = Path(test_file)
    if not path.is_absolute():
        path = BASE_PATH / test_file
    
    if not path.exists():
        return ""
    
    try:
        spec = importlib.util.spec_from_file_location("paper_module", path)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        
        # Find test classes with academic_paper
        for name in dir(module):
            obj = getattr(module, name)
            if isinstance(obj, type) and hasattr(obj, "academic_paper"):
                paper = getattr(obj, "academic_paper", None)
                if paper and isinstance(paper, str):
                    return paper.strip()
                    
    except Exception:
        # Fall back to regex extraction
        content = path.read_text(encoding="utf-8")
        # Match triple-quoted string assigned to academic_paper
        match = re.search(
            r'academic_paper\s*=\s*"""(.*?)"""',
            content,
            re.DOTALL
        )
        if match:
            return match.group(1).strip()
    
    return ""


def _validate_paper_property(test_file: str) -> Dict[str, Any]:
    """
    Validate the academic_paper property on a test class.
    
    Checks:
    1. Paper exists
    2. Word count is between 400 and 700
    3. Honesty standards (no overclaiming, limitations acknowledged)
    
    Args:
        test_file: Path to the test file
        
    Returns:
        Validation result dict
    """
    result = {
        "valid": False,
        "file": test_file,
        "has_paper": False,
        "word_count": 0,
        "word_limit": ACADEMIC_PAPER_WORD_LIMIT,
        "word_count_valid": False,
        "honesty_check": None,
        "honesty_passed": False,
        "issues": [],
        "suggestions": [],
    }
    
    # Extract paper
    paper = _extract_paper_property(test_file)
    
    if not paper:
        result["issues"].append("No academic_paper property found")
        result["suggestions"].append("Add academic_paper property to test class")
        return result
    
    result["has_paper"] = True
    
    # Check word count
    word_count = len(paper.split())
    result["word_count"] = word_count
    
    if word_count > ACADEMIC_PAPER_WORD_LIMIT:
        result["issues"].append(f"Paper is {word_count} words (limit: {ACADEMIC_PAPER_WORD_LIMIT})")
        result["suggestions"].append("Reduce paper length to 700 words or less")
    elif word_count < PAPER_WORD_MIN:
        result["issues"].append(f"Paper is too short ({word_count} words, minimum: {PAPER_WORD_MIN})")
        result["suggestions"].append("Expand paper with proper structure (see template)")
    else:
        result["word_count_valid"] = True
    
    # Check honesty
    honesty = validate_honesty(paper)
    result["honesty_check"] = honesty
    result["honesty_passed"] = honesty["passed"]
    
    if not honesty["passed"]:
        result["issues"].extend(honesty["recommendations"])
    
    # Final validity
    result["valid"] = (
        result["has_paper"] and 
        result["word_count_valid"] and 
        result["honesty_passed"]
    )
    
    return result


