def validate_honesty(paper_text: str) -> Dict[str, Any]:
    """
    Validate intellectual honesty of the paper.
    
    Returns:
        Dictionary with validation results
    """
    text_lower = paper_text.lower()
    
    # Check for forbidden phrases
    found_forbidden = []
    for phrase in HONESTY_CHECKS["forbidden_phrases"]:
        if phrase in text_lower:
            found_forbidden.append(phrase)
    
    # Check for required elements
    missing_required = []
    for element in HONESTY_CHECKS["required_elements"]:
        if element not in text_lower:
            missing_required.append(element)
    
    # Check for preferred phrases (at least one)
    found_preferred = []
    for phrase in HONESTY_CHECKS["preferred_phrases"]:
        if phrase in text_lower:
            found_preferred.append(phrase)
    
    # Calculate honesty score
    score = 100
    score -= len(found_forbidden) * 15  # Penalty for forbidden phrases
    score -= len(missing_required) * 10  # Penalty for missing elements
    if not found_preferred:
        score -= 10  # Penalty for no preferred phrases
    score = max(0, min(100, score))
    
    return {
        "score": score,
        "passed": score >= 70 and not found_forbidden,
        "forbidden_phrases_found": found_forbidden,
        "missing_required_elements": missing_required,
        "preferred_phrases_used": found_preferred,
        "recommendations": _get_honesty_recommendations(
            found_forbidden, missing_required, found_preferred
        ),
    }


def _get_honesty_recommendations(
    forbidden: List[str],
    missing: List[str],
    preferred: List[str],
) -> List[str]:
    """Generate recommendations for improving honesty."""
    recs = []
    
    for phrase in forbidden:
        recs.append(f"Remove or rephrase: '{phrase}' (overclaiming)")
    
    for element in missing:
        recs.append(f"Add discussion of: {element}")
    
    if not preferred:
        recs.append("Use more measured language (e.g., 'the model calculates', 'this is consistent with')")
    
    return recs


